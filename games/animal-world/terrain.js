const built = {};
// 지역 지도 → base(지도 글자 그대로의 지형) · kind(계단 칸은 'step') · sub(높이, 작은 계단 단위)
// 작은 계단: 높이가 다른 지형 사이를 한 칸(8방향)에 한 계단(1/3단계)씩 잇는다.
//  · 더 높은 지형은 낮은 쪽 칸을 끌어올린다(높은 언덕 → 낮은 언덕 → 평지·길 순서로, 앞에서 정한 높이를 기준으로).
//  · 저지대·물은 둘레 칸(평지·길·언덕)을 끌어내린다.
// 그래서 계단은 언덕 바깥(평지 쪽)과 저지대 바깥에 생기고 언덕 윗면·저지대 안쪽은 그대로다. 낮은 언덕이 저지대에 바로 닿는 곳은 언덕 쪽이 계단으로 내려가고,
// 높은 언덕은 내려가지 않아 저지대 바로 옆이면 절벽으로 남는다(바닷가 모래 언덕·바위 곶). 봉우리는 계단 없이 솟고(둘레는 높은 언덕 높이로 친다),
// 끌어올림과 끌어내림이 겹치면 내려가는 쪽을 따라 턱을 더 높은 지형 가장자리로 보낸다
const REACH = 6; // 높은 언덕(6계단)에서 평지(0)까지 필요한 거리
function build(rid) {
  if (built[rid]) return built[rid];
  const rows = MAPS[rid], N = GRID * GRID, base = new Array(N).fill('flat');
  if (rows) for (let y = 0; y < GRID; y++) for (let x = 0; x < GRID; x++) base[y * GRID + x] = CH[rows[y]?.[x]] ?? 'flat';
  const own = base.map((k) => TERRAIN[k].h * SUB), sub = own.slice(), kind = base.slice();
  const near = (i, f) => { // REACH 안의 칸 j와 거리 d(8방향)
    const x = i % GRID, y = (i - x) / GRID;
    for (let dy = -REACH; dy <= REACH; dy++) for (let dx = -REACH; dx <= REACH; dx++) {
      const xx = x + dx, yy = y + dy;
      if ((dx || dy) && xx >= 0 && yy >= 0 && xx < GRID && yy < GRID) f(yy * GRID + xx, Math.max(Math.abs(dx), Math.abs(dy)));
    }
  };
  const settle = (kinds, pullers, sink = true) => {
    for (let i = 0; i < N; i++) {
      if (!kinds.includes(base[i])) continue;
      let lo = -Infinity, hi = Infinity;
      near(i, (j, d) => {
        const k = base[j];
        if (pullers.includes(k)) { const s = k === 'peak' ? TERRAIN.high.h * SUB : sub[j]; if (s > own[i]) lo = Math.max(lo, s - d); }
        if (sink && (k === 'low' || k === 'water')) hi = Math.min(hi, own[j] + d);
      });
      sub[i] = lo <= hi ? Math.min(Math.max(own[i], lo), hi) : hi; // 겹치면 내려가는 쪽을 따른다(턱은 더 높은 지형 가장자리에 남는다)
    }
  };
  settle(['hill'], ['high', 'peak']);
  settle(['flat', 'path'], ['hill', 'high', 'peak']);
  for (let i = 0; i < N; i++) if (sub[i] !== own[i] && base[i] !== 'path') kind[i] = 'step'; // 길은 높이만 따라가고 길로 남는다
  return (built[rid] = { base, kind, sub });
}
// 지역 지도를 칸 배열(지형 이름, 계단 칸은 'step')로. 지도가 없는 지역은 모두 평지
export const terrainOf = (rid) => build(rid).kind;
// 계단을 만들기 전 지도 지형(색·장식용)
export const baseOf = (rid) => build(rid).base;
const inGrid = (x, y) => x >= 0 && y >= 0 && x < GRID && y < GRID;
export const kindAt = (rid, x, y) => (inGrid(x, y) ? terrainOf(rid)[y * GRID + x] : null);
// 칸 높이(단계 단위, 작은 계단이면 1/3씩). 화면 높이 = heightAt × LEVEL
export const heightAt = (rid, x, y) => (inGrid(x, y) ? build(rid).sub[y * GRID + x] / SUB : 0);
export const hasWater = (rid) => terrainOf(rid).includes('water');

// 물건을 놓을 수 있는 지형(앞에 있을수록 먼저 권하는 자리)
// 은신처·먹이·물그릇 → 낮은 언덕·평지 / 놀이·관람 → 높은 언덕·평지 / 물 자연물 → 저지대 / 헤엄치는 물 → 물·저지대 / 걷는 바닥 → 평지·저지대
const WATER_BODY = new Set(['puddle', 'pond', 'oasis', 'bigoasis', 'icehole']);
const ON_WATER = new Set(['buoy']);
export function allowedOn(id) {
  const d = ITEMS[id];
  if (!d) return [];
  if (ON_WATER.has(id)) return ['water'];
  if (d.swim) return ['water', 'low'];
  if (WATER_BODY.has(id)) return ['low'];
  if (d.walk) return ['flat', 'low'];
  if (!Object.keys(d.give).length) return ['high', 'flat'];
  return ['hill', 'flat'];
}
// 물건 하나가 덮는 칸이 모두 허용 지형이고 높이가 같은가
export function terrainFits(rid, id, x, y) {
  const d = ITEMS[id], ok = allowedOn(id);
  let h = null;
  for (let yy = y; yy < y + d.h; yy++) for (let xx = x; xx < x + d.w; xx++) {
    const k = kindAt(rid, xx, yy);
    if (!k || !ok.includes(k)) return false;
    if (h === null) h = TERRAIN[k].h; else if (TERRAIN[k].h !== h) return false;
  }
  return true;
}
